export default {
  async fetch(request, env) {
    if (request.method === "OPTIONS") {
      return new Response(null, { status: 204, headers: corsHeaders() });
    }

    const url = new URL(request.url);

    if (url.pathname === "/login" || url.pathname === "/api/login") {
      return handleLogin(request, env, url);
    }

    if (url.pathname === "/invitation" || url.pathname === "/api/invitation") {
      return handleInvitationSession(request, env);
    }

    if (url.pathname === "/rsvp" || url.pathname === "/api/rsvp") {
      return handleRsvp(request, env);
    }

    return jsonResponse({ error: "Not found" }, 404);
  }
};

async function handleLogin(request, env, url) {
  let rawFirstName = "";
  let firstName = "";
  let lastName = "";
  let password = "";

  if (request.method === "GET") {
    rawFirstName = String(url.searchParams.get("firstName") || "").trim();
    firstName = normalize(rawFirstName);
    lastName = normalize(url.searchParams.get("lastName") || "");
    password = String(url.searchParams.get("password") || "");
  } else if (request.method === "POST") {
    let body;

    try {
      body = await request.json();
    } catch {
      return jsonResponse({ error: "Invalid request" }, 400);
    }

    rawFirstName = String(body.firstName || "").trim();
    firstName = normalize(rawFirstName);
    lastName = normalize(body.lastName || "");
    password = String(body.password || "");
  } else {
    return jsonResponse({ error: "Method not allowed" }, 405);
  }

  if (!firstName || !lastName || !password) {
    return jsonResponse({ error: "Invalid name or password" }, 401);
  }

  const suppliedHash = await sha256(password);

  if (suppliedHash !== PASSWORD_HASH) {
    return jsonResponse({ error: "Invalid name or password" }, 401);
  }

  const loginRecord = LOGIN_LOOKUP[`${firstName}|${lastName}`];

  if (!loginRecord || !PARTIES[loginRecord.partyKey]) {
    return jsonResponse({ error: "Invalid name or password" }, 401);
  }

  const sessionToken = await createSessionToken({
    partyKey: loginRecord.partyKey,
    loginDisplayName: loginRecord.displayName,
    loginFirstName: displayFirstName(rawFirstName, loginRecord.displayName),
    exp: SESSION_EXPIRES_AT
  }, env.SESSION_SECRET || PASSWORD_HASH);

  try {
    const payload = await buildInvitationPayload(env, {
      partyKey: loginRecord.partyKey,
      loginDisplayName: loginRecord.displayName,
      loginFirstName: displayFirstName(rawFirstName, loginRecord.displayName),
      sessionToken
    });

    return jsonResponse(payload, 200);
  } catch (error) {
    console.error("Could not load D1 invitation data", error);
    return jsonResponse({
      error: "We couldn't load your saved invitation details right now. Please try again."
    }, 503);
  }
}

async function handleInvitationSession(request, env) {
  if (request.method !== "POST") {
    return jsonResponse({ error: "Method not allowed" }, 405);
  }

  let body;

  try {
    body = await request.json();
  } catch {
    return jsonResponse({ error: "Invalid request" }, 400);
  }

  const sessionToken = String(body.sessionToken || "");
  const session = await verifySessionToken(
    sessionToken,
    env.SESSION_SECRET || PASSWORD_HASH
  );

  if (!session || !session.partyKey || !PARTIES[session.partyKey]) {
    return jsonResponse({
      error: "Your invitation session has expired. Please sign in again."
    }, 401);
  }

  try {
    const payload = await buildInvitationPayload(env, {
      partyKey: session.partyKey,
      loginDisplayName: session.loginDisplayName || PARTIES[session.partyKey].party,
      loginFirstName: session.loginFirstName || firstNameFromDisplay(session.loginDisplayName),
      sessionToken
    });

    return jsonResponse(payload, 200);
  } catch (error) {
    console.error("Could not refresh invitation from D1", error);
    return jsonResponse({
      error: "We couldn't refresh your saved response right now. Please try again."
    }, 503);
  }
}

