async function ensureRsvpSchema(env) {
  if (!env.DB) {
    throw new Error("D1 binding DB is not configured.");
  }

  if (!rsvpSchemaReadyPromise) {
    rsvpSchemaReadyPromise = env.DB.batch([
      env.DB.prepare(`
        CREATE TABLE IF NOT EXISTS rsvp_responses (
          party_key TEXT PRIMARY KEY,
          party_name TEXT NOT NULL,
          invite_type TEXT NOT NULL,
          attending TEXT NOT NULL,
          guests_json TEXT NOT NULL DEFAULT '[]',
          email TEXT NOT NULL,
          dietary TEXT NOT NULL DEFAULT 'None',
          phone TEXT NOT NULL DEFAULT '',
          message TEXT NOT NULL DEFAULT '',
          login_display_name TEXT NOT NULL,
          first_submitted_at TEXT NOT NULL,
          updated_at TEXT NOT NULL,
          submission_id TEXT NOT NULL
        )
      `),
      env.DB.prepare(`
        CREATE TABLE IF NOT EXISTS rsvp_history (
          id INTEGER PRIMARY KEY AUTOINCREMENT,
          submission_id TEXT NOT NULL UNIQUE,
          party_key TEXT NOT NULL,
          party_name TEXT NOT NULL,
          invite_type TEXT NOT NULL,
          attending TEXT NOT NULL,
          guests_json TEXT NOT NULL DEFAULT '[]',
          email TEXT NOT NULL,
          dietary TEXT NOT NULL DEFAULT 'None',
          phone TEXT NOT NULL DEFAULT '',
          message TEXT NOT NULL DEFAULT '',
          login_display_name TEXT NOT NULL,
          submitted_at TEXT NOT NULL
        )
      `),
      env.DB.prepare(`
        CREATE INDEX IF NOT EXISTS idx_rsvp_history_party_key
        ON rsvp_history (party_key)
      `)
    ]).catch(error => {
      rsvpSchemaReadyPromise = null;
      throw error;
    });
  }

  await rsvpSchemaReadyPromise;
}

async function getSavedRsvp(env, partyKey) {
  await ensureRsvpSchema(env);

  const row = await env.DB.prepare(`
    SELECT
      party_key,
      party_name,
      invite_type,
      attending,
      guests_json,
      email,
      dietary,
      phone,
      message,
      login_display_name,
      first_submitted_at,
      updated_at,
      submission_id
    FROM rsvp_responses
    WHERE party_key = ?
  `).bind(partyKey).first();

  return row ? rowToRsvp(row) : null;
}

