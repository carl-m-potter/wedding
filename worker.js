function rowToRsvp(row) {
  let guests = [];

  try {
    guests = JSON.parse(row.guests_json || "[]");
    if (!Array.isArray(guests)) guests = [];
  } catch {
    guests = [];
  }

  return {
    attending: row.attending,
    guests,
    email: row.email || "",
    dietary: row.dietary || "None",
    phone: row.phone || "",
    message: row.message || "",
    firstSubmittedAt: row.first_submitted_at,
    updatedAt: row.updated_at,
    submissionId: row.submission_id
  };
}

function displayFirstName(rawFirstName, loginDisplayName) {
  const clean = String(rawFirstName || "").trim();
  if (clean) {
    return clean
      .split(/\s+/)[0]
      .replace(/\b[a-z]/g, letter => letter.toUpperCase());
  }

  return firstNameFromDisplay(loginDisplayName);
}

function firstNameFromDisplay(displayName) {
  if (displayName === "Auntie Pat") return "Pat";
  return String(displayName || "there").trim().split(/\s+/)[0] || "there";
}

function parseSelectedGuests(value) {
  const text = String(value || "").trim();
  if (!text || text.toLowerCase() === "none") return [];

  return text
    .split(",")
    .map(name => name.trim())
    .filter(Boolean);
}

function cleanText(value, maxLength) {
  return String(value || "").trim().slice(0, maxLength);
}

function isValidEmail(value) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value) && value.length <= 320;
}

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

async function createSessionToken(payload, secret) {
  const encodedPayload = base64UrlEncode(
    new TextEncoder().encode(JSON.stringify(payload))
  );
  const signature = await signValue(encodedPayload, secret);
  return `${encodedPayload}.${signature}`;
}

async function verifySessionToken(token, secret) {
  try {
    const [encodedPayload, signature] = String(token || "").split(".");
    if (!encodedPayload || !signature) return null;

    const valid = await verifyValue(encodedPayload, signature, secret);
    if (!valid) return null;

    const json = new TextDecoder().decode(base64UrlDecode(encodedPayload));
    const payload = JSON.parse(json);

    if (!payload.exp || payload.exp < Math.floor(Date.now() / 1000)) {
      return null;
    }

    return payload;
  } catch {
    return null;
  }
}

async function signValue(value, secret) {
  const key = await importHmacKey(secret);
  const signature = await crypto.subtle.sign(
    "HMAC",
    key,
    new TextEncoder().encode(value)
  );
  return base64UrlEncode(new Uint8Array(signature));
}

async function verifyValue(value, signature, secret) {
  const key = await importHmacKey(secret);
  return crypto.subtle.verify(
    "HMAC",
    key,
    base64UrlDecode(signature),
    new TextEncoder().encode(value)
  );
}

async function importHmacKey(secret) {
  return crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(secret),
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign", "verify"]
  );
}

function base64UrlEncode(bytes) {
  let binary = "";
  bytes.forEach(byte => {
    binary += String.fromCharCode(byte);
  });

  return btoa(binary)
    .replace(/\+/g, "-")
    .replace(/\//g, "_")
    .replace(/=+$/g, "");
}

function base64UrlDecode(value) {
  const base64 = value
    .replace(/-/g, "+")
    .replace(/_/g, "/")
    .padEnd(Math.ceil(value.length / 4) * 4, "=");

  const binary = atob(base64);
  return Uint8Array.from(binary, char => char.charCodeAt(0));
}

function normalize(value) {
  return String(value).trim().toLowerCase().replace(/\s+/g, " ");
}

async function sha256(value) {
  const data = new TextEncoder().encode(value);
  const digest = await crypto.subtle.digest("SHA-256", data);

  return [...new Uint8Array(digest)]
    .map(byte => byte.toString(16).padStart(2, "0"))
    .join("");
}

async function safeResponseText(response) {
  try {
    return (await response.text()).slice(0, 1000);
  } catch {
    return "";
  }
}

function corsHeaders() {
  return {
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type",
    "Cache-Control": "no-store"
  };
}

function jsonResponse(data, status) {
  return new Response(JSON.stringify(data), {
    status,
    headers: {
      "Content-Type": "application/json; charset=utf-8",
      ...corsHeaders()
    }
  });
}
